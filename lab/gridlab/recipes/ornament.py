# ---- Truchet ---------------------------------------------------------------------

def _tile(rows: list[str]) -> np.ndarray:
    return np.array([[c == "#" for c in r] for r in rows], bool)


# 5x5 tiles placed at stride 4, so neighbouring tiles share their connector cells
# (N = (x2,y0), E = (x4,y2), S = (x2,y4), W = (x0,y2)). Only the NW/vertical orientation is listed;
# the other orientations are generated by rotation.
_BASE = {
    "arc": _tile(["..#..",
                  ".#...",
                  "#....",
                  ".....",
                  "....."]),
    "round": _tile(["..#..",
                    "..#..",
                    "##...",
                    ".....",
                    "....."]),
    "smith": _tile(["..#..",
                    ".#...",
                    "#...#",
                    "...#.",
                    "..#.."]),
    "bridge": _tile(["..#..",
                     "..#..",
                     "..#..",
                     "..#..",
                     "..#.."]),
    "bead": _tile(["..#..",
                   "..#..",
                   ".#.#.",
                   "..#..",
                   "..#.."]),
    "hook": _tile(["..#..",
                   "..#..",
                   ".#.#.",
                   ".....",
                   "....."]),
    "cross": _tile(["..#..",
                    "..#..",
                    "#####",
                    "..#..",
                    "..#.."]),
    "empty": np.zeros((5, 5), bool),
}


# 3x3 tiles at stride 2 (fine grain): connectors N=(1,0) E=(2,1) S=(1,2) W=(0,1)
_FINE = {
    "arc": _tile([".#.",
                  "#..",
                  "..."]),
    "elbow": _tile([".#.",
                    "##.",
                    "..."]),
    "ring": _tile([".#.",
                   "#.#",
                   ".#."]),
    "bridge": _tile([".#.",
                     ".#.",
                     ".#."]),
    "hook": _tile([".#.",
                   ".#.",
                   "..."]),
    "cross": _tile([".#.",
                    "###",
                    ".#."]),
    "empty": np.zeros((3, 3), bool),
}

GRAIN_WEIGHTS = {
    "coarse": {"arc": 1.0, "round": 1.0, "smith": 0.8, "bridge": 0.35, "bead": 0.4, "hook": 0.15, "cross": 0.1},
    "fine": {"arc": 1.6, "elbow": 0.5, "ring": 0.5, "bridge": 0.25, "hook": 0.15, "cross": 0.1},
}


def _conn(t: np.ndarray) -> tuple[int, int, int, int]:
    c = t.shape[0] // 2
    e = t.shape[0] - 1
    return int(t[0, c]), int(t[c, e]), int(t[e, c]), int(t[c, 0])


def _tileset(base: dict) -> list[tuple[str, np.ndarray, tuple]]:
    out, seen = [], set()
    for name, b in base.items():
        for k in range(4):
            t = np.rot90(b, k)
            key = (name, t.tobytes())
            if key in seen:
                continue
            seen.add(key)
            out.append((name, t, _conn(t)))
    return out


TILESETS = {"coarse": (_tileset(_BASE), 4), "fine": (_tileset(_FINE), 2)}


@recipe("truchet_sparse", section="ornament", title="Sparse Truchet",
        description="Pixel Truchet tiles on a lattice where neighbours share connector cells: fine grain = 3x3 "
                    "tiles of diagonal arcs, elbows and tiny rings (pure slime-mould bridges); coarse = 5x5 tiles "
                    "with Smith double-arcs, bridges and beads. Chosen on the fundamental quadrant only, "
                    "edge-matched so every stroke continues (chains and loops instead of stubs), sparse, inside a "
                    "silhouette, then mirrored cell-exactly.",
        params={
            "grain": Param("fine", choices=["fine", "coarse"]),
            "tiles_x": Param(7, 3, 15, 1),
            "tiles_y": Param(11, 3, 21, 1),
            "silhouette": Param("capsule", choices=["capsule", "oval", "octagon", "ring", "diamond", "rrect"]),
            "density": Param(0.7, 0.1, 1.0, 0.05, description="chance a tile is not empty"),
            "style": Param("mixed", choices=["diag", "round", "mixed"]),
            "band": Param(3, 0, 8, 1, description="tiles from the edge that may be filled (0 = all)"),
            "core": Param("none", choices=["none", "bridge", "cross"]),
            "curate": Param(8, 1, 24, 1, description="tilings tried; best balance of few pieces and fill wins"),
        },
        tags=["tiles", "d2"])
def truchet_sparse(seed: int, grain: str, tiles_x: int, tiles_y: int, silhouette: str, density: float, style: str,
                   band: int, core: str, curate: int) -> Design:
    rng = np.random.default_rng(seed)
    best = None
    for k in range(curate):
        d = _truchet_once(rng, grain, tiles_x, tiles_y, silhouette, density, style, band, core)
        m = d.layers[0].mask
        pieces = morph.label(m, 8)[1]
        score = -4 * max(0, pieces - 2) - 1.5 * (pieces > 1) + 80 * min(m.sum() / max(m.size, 1), 0.3)
        if m.sum() < 12:
            score -= 1000
        if best is None or score > best[0]:
            best = (score, d, k)
    score, d, k = best
    d.notes += f" Best of {curate} tilings (#{k})."
    return d


def _truchet_once(rng, grain, tiles_x, tiles_y, silhouette, density, style, band, core) -> Design:
    tiles, st = TILESETS[grain]
    W, H = st * tiles_x + 1, st * tiles_y + 1
    sil_t = ca.silhouette(silhouette, tiles_y, tiles_x, thickness=max(1.6, min(tiles_x, tiles_y) / 3))
    dist_t = M.distance_from_edge(sil_t)
    inside = sil_t & ((dist_t <= band + 0.01) if band else True)
    cxs, cys = (tiles_x - 1) // 2, (tiles_y - 1) // 2
    weights = dict(GRAIN_WEIGHTS[grain])
    if style == "diag":
        weights.pop("round", None)
        weights.pop("elbow", None)
    elif style == "round":
        weights.pop("arc", None)
        weights["elbow"] = weights.get("elbow", 0) + 1.0 if grain == "fine" else 0
    empty = ("empty", np.zeros((st + 1, st + 1), bool), (0, 0, 0, 0))
    choice: dict = {}

    def conn_of(tx, ty):
        if not (0 <= tx < tiles_x and 0 <= ty < tiles_y) or not inside[ty, tx]:
            return (0, 0, 0, 0)
        return choice[(tx, ty)][2] if (tx, ty) in choice else None

    for ty in range(cys + 1):
        for tx in range(cxs + 1):
            if not inside[ty, tx]:
                choice[(tx, ty)] = empty
                continue
            north, west = conn_of(tx, ty - 1), conn_of(tx - 1, ty)
            need_n = north[2] if north is not None else None
            need_w = west[1] if west is not None else None
            east_out = tx + 1 >= tiles_x or not inside[ty, tx + 1]
            south_out = ty + 1 >= tiles_y or not inside[ty + 1, tx]
            # a tile on a mirror axis meets its own mirror image: E must equal W (resp. S = N)
            on_vaxis = tiles_x % 2 == 1 and tx == cxs
            on_haxis = tiles_y % 2 == 1 and ty == cys
            cands, ws = [], []
            for t in tiles:
                name, arr, (n, e, s_, w) = t
                if (need_n is not None and n != need_n) or (need_w is not None and w != need_w):
                    continue
                if (east_out and e) or (south_out and s_) or (on_vaxis and e != w) or (on_haxis and s_ != n):
                    continue
                wt = (1 - density) * 2.5 if name == "empty" else density * weights.get(name, 0.0)
                if wt > 0:
                    cands.append(t)
                    ws.append(wt)
            if not cands:
                cands, ws = [empty], [1.0]
            ws = np.array(ws) / np.sum(ws)
            choice[(tx, ty)] = cands[int(rng.choice(len(cands), p=ws))]
    m = np.zeros((H, W), bool)
    hist = []
    for (tx, ty), (name, arr, _) in sorted(choice.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        m[st * ty:st * ty + st + 1, st * tx:st * tx + st + 1] |= arr
        if tx == cxs:
            hist.append(symmetry.symmetrize_d2(m.copy()))
    m = symmetry.symmetrize_d2(m)
    if core != "none":
        cy, cx = (H - 1) // 2, (W - 1) // 2
        cm = np.zeros_like(m)
        cm[2:H - 2, cx] = True
        if core == "cross":
            cm[cy, 2:W - 2] = True
        cm &= morph.dilate(ca.silhouette(silhouette, H, W) & ~morph.dilate(m, 1, 8), 0) | m
        lab, _ = morph.label(cm, 4)
        if lab[cy, cx]:
            m |= lab == lab[cy, cx]
    out = ca.lace_clean(m, "d2", min_size=5)
    out = morph.keep_largest(out, 8, 8)
    d = Design.from_masks({1: out})
    set_frames(d, [(f"row {i}", {1: h}) for i, h in enumerate(hist)] + [("final", {1: out})])
    used = sorted({v[0] for v in choice.values()})
    d.notes = (f"{grain} grain: {tiles_x}x{tiles_y} tiles (stride {st}, shared connectors) in a {silhouette}, band "
               f"{band or 'all'}, density {density}, style {style}; edge-matched on the quadrant then mirrored. "
               f"tiles used: {used}.")
    return d


# ---- kogin rosette ---------------------------------------------------------------

RING_STYLES = ["line", "step", "dash", "teeth", "flowers", "double"]


def _ring(style: str, R: int, r: np.ndarray, t: np.ndarray, k: int) -> np.ndarray:
    """Cells of one diamond ring of L1 radius R. t = position along the ring (|dx| in the quadrant)."""
    line = r == R
    if style == "line":
        return line
    if style == "step":
        return (r == R) | (r == R + 1)
    if style == "dash":
        return line & ((t // k) % 2 == 0)
    if style == "teeth":
        return line | (((r == R + 1) | (r == R + 2)) & (t % k == 0))
    if style == "flowers":
        on = line & (t % k == 0)
        return line | (morph.dilate(on, 1, 4) & ~on & (r != R))
    if style == "double":
        return line | (r == R + 2)
    raise ValueError(style)


@recipe("kogin_rosette", section="ornament", title="Kogin rosette",
        description="A 4-fold grammar of concentric diamonds (kogin-zashi / sashiko feel): each ring gets a stitch "
                    "style (line, stepped, dashed, teeth, little flowers, double), rings are tied by rays along the "
                    "axes or diagonals, with a small centre glyph. Crisp and calm: a natural top layer or brooch.",
        params={
            "size": Param(21, 9, 41, 2),
            "stretch": Param(0, 0, 12, 1, description="extra rows at the centre: elongated lozenge (D2)"),
            "rings": Param(3, 1, 6, 1),
            "gap": Param(4, 2, 6, 1, description="typical radial distance between rings"),
            "rays": Param("auto", choices=["auto", "axis", "diag", "both"]),
            "centre": Param("auto", choices=["auto", "dot", "cross", "diamond", "flower"]),
            "clip": Param("diamond", choices=["diamond", "octagon", "circle"]),
        },
        tags=["ornament", "d4", "top"])
def kogin_rosette(seed: int, size: int, stretch: int, rings: int, gap: int, rays: str, centre: str,
                  clip: str) -> Design:
    rng = np.random.default_rng(seed)
    best = None
    for k in range(8):  # restraint: re-roll the grammar while the rosette is too dense
        d, fill = _kogin_once(rng, size, stretch, rings, gap, rays, centre, clip)
        if best is None or abs(fill - 0.33) < abs(best[1] - 0.33):
            best = (d, fill)
        if 0.22 <= fill <= 0.42:
            break
    return best[0]


def _kogin_once(rng, size, stretch, rings, gap, rays, centre, clip):
    N = size
    W, H = N, N + 2 * stretch
    cy, cx = (H - 1) / 2, (W - 1) / 2
    y, x = np.mgrid[0:H, 0:W]
    adx = np.abs(x - cx).astype(int)
    ady = np.maximum(0, np.abs(y - cy) - stretch).astype(int)
    r = adx + ady
    t = np.minimum(adx, ady)  # distance from the nearest axis along the ring: D4-symmetric
    Rmax = (N - 1) // 2
    # radii from the outside in
    radii = []
    R = Rmax - 1 if clip == "diamond" else Rmax - 1
    for i in range(rings):
        if R < 2:
            break
        radii.append(R)
        R -= gap + int(rng.integers(-1, 2)) if i else gap + int(rng.integers(0, 2))
    m = np.zeros((H, W), bool)
    styles = []
    hist = []
    for i, R in enumerate(radii):
        if i == 0:
            st = str(rng.choice(["line", "step", "double", "teeth"], p=[0.45, 0.15, 0.15, 0.25]))
            if st in ("teeth", "double"):
                R -= 2
                radii[0] = R
        else:
            st = str(rng.choice(RING_STYLES, p=[0.2, 0.05, 0.3, 0.15, 0.25, 0.05]))
        k = int(rng.choice([2, 3, 4])) if st != "dash" else int(rng.choice([1, 2]))
        ring = _ring(st, R, r, t, k)
        # teeth on the outer ring point inward instead of out
        if i == 0 and st == "teeth":
            ring = (r == R + 2) | (((r == R + 1) | (r == R)) & (t % k == 0))
        m |= ring
        styles.append(f"{st}{k if st in ('dash', 'teeth', 'flowers') else ''}@{R}")
        hist.append(m.copy())
    # centre glyph
    cg = centre if centre != "auto" else str(rng.choice(["dot", "cross", "diamond", "flower"]))
    inner_R = radii[-1] if radii else Rmax
    if cg == "dot":
        m |= r == 0
        m |= (r == 1) & ((adx == 0) | (ady == 0))
    elif cg == "cross":
        arm = max(1, min(inner_R - 2, 3))
        m |= ((adx == 0) | (ady == 0)) & (r <= arm)
    elif cg == "diamond":
        m |= (r == max(1, min(2, inner_R - 2))) | (r == 0)
    elif cg == "flower":
        m |= (r == 1) | (r == 0)
        m &= ~((r == 0))
        m |= (r == 2) & (t == 0)
    hist.append(m.copy())
    # rays tying ring i to ring i+1 (and the innermost ring to the centre)
    ray_kind = rays if rays != "auto" else str(rng.choice(["axis", "diag", "both"], p=[0.45, 0.35, 0.2]))
    span_hi = radii[0] if radii else Rmax
    axis_ray = (t == 0)
    diag_ray = (np.abs(adx - ady) == 0) | (np.abs(adx - ady) == 1) & False
    bounds = list(radii) + [0]
    for i in range(len(bounds) - 1):
        hi, lo = bounds[i], bounds[i + 1]
        seg = (r <= hi) & (r >= lo)
        kind_i = ray_kind
        if ray_kind == "both":
            kind_i = "axis" if i % 2 == 0 else "diag"
        if kind_i == "axis":
            m |= seg & axis_ray
        else:
            m |= seg & (adx == ady) if not stretch else seg & (adx == ady)
            if stretch:
                m |= seg & axis_ray & (adx == 0)
    del span_hi, diag_ray
    if clip == "octagon":
        m &= ca.octagon(H, W)
    elif clip == "circle":
        m &= M.ellipse(H, W)
    # ornament, not lace: 2x2 knots where rays cross rings are allowed (junction nodes)
    out = morph.remove_small(m, 3, 8)
    out = morph.keep_largest(out, 8, 1) if morph.label(out, 8)[1] > 1 else out
    masks = {1: out}
    d = Design.from_masks(masks)
    set_frames(d, [(f"ring {i}", {1: h}) for i, h in enumerate(hist)] + [("final", masks)])
    d.notes = (f"rings {styles}, centre {cg}, rays {ray_kind}, clip {clip}"
               + (f", stretch {stretch}" if stretch else "") + ". t = distance to nearest axis keeps it D4.")
    return d, float(out.sum() / max(1, (r <= Rmax).sum()))


# ---- hitomezashi name sigil (own idea) -----------------------------------------------------

@recipe("name_sigil", section="ornament", title="Hitomezashi name sigil",
        description="Own idea: hitomezashi (Japanese 'one-stitch' sashiko) as a sigil. The letters of a word are "
                    "hashed into two bit rows; each bit decides whether a row/column of running stitches starts on "
                    "or off. Stitches are cells between lattice nodes, so strokes are 1 cell wide and never form "
                    "2x2 blocks. Mirrored bit rows make it symmetric; a silhouette crops it into an amulet.",
        params={
            "word": Param("", description="any text; empty = derived from the seed"),
            "size": Param(10, 4, 20, 1, description="lattice nodes per side (canvas = 2*size+1)"),
            "aspect": Param(1.0, 0.5, 1.0, 0.05),
            "silhouette": Param("octagon", choices=["octagon", "oval", "capsule", "diamond", "ring", "square"]),
            "sym": Param("d4", choices=["d2", "d4"]),
            "frame": Param(True),
            "prune": Param(0, 0, 3, 1, description="spur pruning passes (removes stitch stubs)"),
        },
        tags=["ornament", "stitch", "d4"])
def name_sigil(seed: int, word: str, size: int, aspect: float, silhouette: str, sym: str, frame: bool,
               prune: int) -> Design:
    text = word or f"seed-{seed}"
    hbits = np.unpackbits(np.frombuffer(hashlib.sha256(text.encode()).digest(), np.uint8))
    nx = max(4, int(round(size * aspect)))
    ny = size
    W, H = 2 * nx + 1, 2 * ny + 1
    if sym == "d4" and W != H:
        sym = "d2"
    a = hbits[:ny + 1].astype(bool)          # row offsets
    b = hbits[64:64 + nx + 1].astype(bool)   # column offsets
    if sym == "d4":
        b = a[:nx + 1].copy()
    # mirror the bit rows so the lattice is symmetric about the centre
    a = np.where(np.arange(ny + 1) > ny // 2, a[::-1], a)
    b = np.where(np.arange(nx + 1) > nx // 2, b[::-1], b)
    m = np.zeros((H, W), bool)
    # horizontal stitches: on lattice row j (y = 2j), cell x = 2i+1 between nodes i, i+1
    for j in range(ny + 1):
        for i in range(nx):
            if (i + int(a[j])) % 2 == 0:
                m[2 * j, 2 * i + 1] = True
    for i in range(nx + 1):
        for j in range(ny):
            if (j + int(b[i])) % 2 == 0:
                m[2 * j + 1, 2 * i] = True
    # nodes: on where a stitch touches them
    node = np.zeros_like(m)
    node[::2, ::2] = True
    m |= node & (morph.neighbour_count(m, 4) > 0)
    raw = m.copy()
    m = ca.symmetrize(m, sym)
    sil = ca.silhouette(silhouette, H, W, thickness=max(3, min(H, W) // 4))
    m &= sil
    if frame:
        m |= sil & ~morph.erode(sil, 1, 4)
    m = ca.prune_spurs(m, prune) if prune else m
    out = ca.lace_clean(m, sym, min_size=4)
    out = morph.keep_largest(out, 8, 4) if not frame else morph.keep_largest(out, 8, 1)
    d = Design.from_masks({1: out})
    set_frames(d, [("lattice", {1: raw}), ("mirrored + cropped", {1: m}), ("final", {1: out})])
    d.notes = (f"hitomezashi from '{text}' (sha256 bits as row/column stitch parity), {nx}x{ny} nodes, {sym}, "
               f"{silhouette}{' + frame' if frame else ''}.")
    return d
